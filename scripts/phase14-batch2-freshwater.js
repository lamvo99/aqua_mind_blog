const MUTATE_BASE = `https://${PROJECT_ID}.api.sanity.io/v${API_VERSION}/data/mutate/${DATASET}`;
const QUERY_BASE = `https://${PROJECT_ID}.api.sanity.io/v${API_VERSION}/data/query/${DATASET}`;

const headers = {
  'Content-Type': 'application/json',
  'Authorization': `Bearer ${TOKEN}`,
};

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

async function createIfNotExists(doc) {
  const id = `species-${slugify(doc.name)}`;
  const body = {
    mutations: [
      {
        createIfNotExists: {
          _id: id,
          _type: 'species',
          ...doc,
        },
      },
    ],
  };
  const res = await fetch(MUTATE_BASE, {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });
  const data = await res.json();
  if (data.error) {
    console.error(`  ERROR [${doc.name}]: ${data.error.message}`);
    return { success: false, id, error: data.error.message };
  }
  console.log(`  OK [${doc.name}] -> ${id}`);
  return { success: true, id, result: data.results?.[0] };
}

async function fetchDoc(id) {
  const q = encodeURIComponent(`*[_id == "${id}"][0]{_id, name}`);
  const res = await fetch(`${QUERY_BASE}?query=${q}`);
  const data = await res.json();
  return data.result;
}

